// Builds base44/shared/data/tx-zips.js from U.S. Census Bureau 2020 files:
//   rel:  https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt
//   gaz:  https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2020_Gazetteer/2020_Gaz_zcta_national.zip
// Usage: node scripts/build-zip-data.mjs <rel.txt> <2020_Gaz_zcta_national.txt>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [relPath, gazPath] = process.argv.slice(2);
if (!relPath || !gazPath) {
  console.error('Usage: node scripts/build-zip-data.mjs <rel.txt> <gaz.txt>');
  process.exit(1);
}

const TX_STATE_FIPS = '48';
const BOM = String.fromCharCode(0xfeff);

// zip -> { county: landAreaInZip }
const parts = new Map();
const relText = readFileSync(relPath, 'utf8');
const relLines = (relText.startsWith(BOM) ? relText.slice(1) : relText).split(/\r?\n/);
const header = relLines[0].split('|');
const col = (name) => header.indexOf(name);
const iZip = col('GEOID_ZCTA5_20');
const iCountyFips = col('GEOID_COUNTY_20');
const iCountyName = col('NAMELSAD_COUNTY_20');
const iLand = col('AREALAND_PART');

for (const line of relLines.slice(1)) {
  if (!line) continue;
  const f = line.split('|');
  const zip = f[iZip];
  if (!zip || !f[iCountyFips]?.startsWith(TX_STATE_FIPS)) continue;
  const county = f[iCountyName].replace(/ County$/, '');
  const land = Number(f[iLand]) || 0;
  if (!parts.has(zip)) parts.set(zip, {});
  const m = parts.get(zip);
  m[county] = (m[county] || 0) + land;
}

const centroids = new Map();
for (const line of readFileSync(gazPath, 'utf8').split(/\r?\n/).slice(1)) {
  const f = line.trim().split(/\t/);
  if (f.length < 7) continue;
  centroids.set(f[0], [Number(Number(f[5]).toFixed(4)), Number(Number(f[6]).toFixed(4))]);
}

// Compact format: zip -> [primaryCounty, lat, lng, ...otherCounties]
const out = {};
for (const zip of [...parts.keys()].sort()) {
  const counties = Object.entries(parts.get(zip))
    .sort((a, b) => b[1] - a[1])
    .map(([name]) => name);
  const [lat, lng] = centroids.get(zip) || [null, null];
  out[zip] = [counties[0], lat, lng, ...counties.slice(1)];
}

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../base44/shared/data/tx-zips.js');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  '// GENERATED by scripts/build-zip-data.mjs from U.S. Census Bureau 2020 ZCTA files. Do not edit by hand.\n' +
    '// Format: zip -> [primaryCounty, lat, lng, ...otherCounties]\n' +
    `export default ${JSON.stringify(out)};\n`,
);
console.log(`Wrote ${Object.keys(out).length} Texas ZIP codes to ${target}`);
